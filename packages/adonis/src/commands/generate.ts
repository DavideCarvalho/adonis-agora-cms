import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { BaseCommand, flags } from '@adonisjs/core/ace';
import type { CommandOptions } from '@adonisjs/core/types/ace';
import type { SchemaSpec } from '../schema/types.js';
import { resolveCliContext } from './shared.js';

/**
 * Emits a self-contained Lucid migration.
 *
 * The compiled spec is embedded in the file, not imported from `config/cms.ts`: an old
 * migration must reproduce the schema it was generated for, even after the config evolves.
 * That is the same reason Payload generates SQL instead of importing the TS schema.
 */
export function renderMigration(
  spec: SchemaSpec,
  timestamp: number,
): { name: string; content: string } {
  const name = `${timestamp}_create_cms_tables.ts`;
  const serialized = JSON.stringify(spec, null, 2);

  const content = `import type { Knex } from 'knex'
import { detectEngine, dropCmsTables, syncCmsSchema } from '@adonis-agora/cms/db'
import type { CmsKnex } from '@adonis-agora/cms/db'
import type { SchemaSpec } from '@adonis-agora/cms/schema'

/**
 * Generated by \`node ace cms:generate\`. The spec below is frozen on purpose — edit the SQL
 * semantics through a new migration, not by re-generating this file.
 */
const spec: SchemaSpec = ${serialized}

export async function up(knex: Knex): Promise<void> {
  const client = knex as unknown as CmsKnex
  await syncCmsSchema(client, spec, {
    engine: detectEngine(client),
    allowDestructive: true,
  })
}

export async function down(knex: Knex): Promise<void> {
  await dropCmsTables(knex as unknown as CmsKnex, spec.tablePrefix)
}
`;

  return { name, content };
}

export default class CmsGenerate extends BaseCommand {
  static override commandName = 'cms:generate';
  static override description = 'Generate a Lucid migration for the current CMS schema';
  static override options: CommandOptions = { startApp: true };

  @flags.string({ description: 'Database connection used to detect the engine', alias: 'c' })
  declare connection: string;

  override async run(): Promise<void> {
    const { spec } = await resolveCliContext(this.app, this.connection);
    const directory = this.app.makePath('database/migrations');
    const { name, content } = renderMigration(spec, Date.now());

    await mkdir(directory, { recursive: true });
    await writeFile(join(directory, name), content, 'utf8');

    this.logger.success(`Created database/migrations/${name}`);
    this.logger.info(`spec hash: ${spec.hash}`);
  }
}
